function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const MAX_ALTERNATIVES = 5;

function buildLibrary(raw: RawExercise[]): ExerciseDefinition[] {
  const withIds = raw.map((ex) => ({ ...ex, id: slugify(ex.name) }));

  const seen = new Set<string>();
  for (const ex of withIds) {
    if (seen.has(ex.id)) {
      throw new Error(`Duplicate exercise id in library: ${ex.id}`);
    }
    seen.add(ex.id);
  }

  return withIds.map((ex) => {
    let alternatives = withIds
      .filter(
        (other) =>
          other.id !== ex.id &&
          other.movementPattern === ex.movementPattern &&
          other.primaryMuscles.some((m) => ex.primaryMuscles.includes(m)),
      )
      .slice(0, MAX_ALTERNATIVES)
      .map((other) => other.id);

    // Fallback: if nothing shares both pattern and primary muscle, offer
    // substitutes that at least train the same primary muscle.
    if (alternatives.length === 0) {
      alternatives = withIds
        .filter(
          (other) =>
            other.id !== ex.id &&
            other.primaryMuscles.some((m) => ex.primaryMuscles.includes(m)),
        )
        .slice(0, 3)
        .map((other) => other.id);
    }

    const def: ExerciseDefinition = {
      id: ex.id,
      name: ex.name,
      primaryMuscles: ex.primaryMuscles,
      secondaryMuscles: ex.secondaryMuscles,
      equipment: ex.equipment,
      movementPattern: ex.movementPattern,
      difficulty: ex.difficulty,
      formCues: ex.formCues,
      commonMistakes: ex.commonMistakes,
      alternatives,
    };
    if (ex.videoUrl) def.videoUrl = ex.videoUrl;
    return def;
  });
}

export const EXERCISE_LIBRARY: ExerciseDefinition[] = buildLibrary(RAW_EXERCISES);

export const EXERCISES_BY_ID: Map<string, ExerciseDefinition> = new Map(
  EXERCISE_LIBRARY.map((ex) => [ex.id, ex]),
);

export function getExercise(id: string): ExerciseDefinition | undefined {
  return EXERCISES_BY_ID.get(id);
}
